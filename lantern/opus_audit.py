"""Private, byte-exact HTTP entity capture for the operator's Opus reviews."""

from contextlib import closing
import hashlib
import http.client
import os
from pathlib import Path
import sqlite3
import stat
import time


class OpusCapture:
    def __init__(self, ledger: Path, request_id: str):
        self.ledger = ledger
        self.request_id = request_id  # Generated by the ledger, never supplied by the model.
        self.directory = ledger.parent / "opus-responses"
        self.path = self.directory / (request_id + ".body")
        self.http_status = None
        self.status = "no_response"
        self.body_bytes = None
        self.sha256 = None
        self.failure = None

    def prepare_directory(self):
        self.directory.mkdir(mode=0o700, exist_ok=True)
        info = self.directory.lstat()
        if not stat.S_ISDIR(info.st_mode) or (os.name == "posix" and info.st_mode & 0o077):
            raise OSError("Opus archive requires a private operator directory")

    def save(self, db):
        db.execute("""UPDATE opus_responses SET http_status=?,capture_status=?,body_bytes=?,sha256=?,
                      failure_code=? WHERE request_id=?""",
                   (self.http_status, self.status, self.body_bytes, self.sha256, self.failure, self.request_id))

    def record_validation(self, code: str):
        with closing(sqlite3.connect(self.ledger)) as db, db:
            db.execute("UPDATE opus_responses SET validation=? WHERE request_id=?", (code, self.request_id))

    def capture(self, response):
        """Archive all received bytes, including error pages and oversized responses."""
        self.http_status = response.status
        partial = self.path.with_suffix(".part")
        digest = hashlib.sha256()
        length = 0
        complete = False
        declared = response.getheader("Content-Length")
        # A chunked response has independent framing even if it also carries Content-Length.
        if response.getheader("Transfer-Encoding") or not (isinstance(declared, str) and declared.isascii()
                                                           and declared.isdecimal() and len(declared) <= 20):
            declared = None
        deadline = time.monotonic() + 60
        try:
            with os.fdopen(os.open(partial, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "wb") as out:
                # read1 makes at most one underlying socket read before checking the deadline.
                read = getattr(response, "read1", response.read)
                while time.monotonic() < deadline:
                    try:
                        chunk = read(64 * 1024)
                    except http.client.IncompleteRead as exc:
                        chunk = exc.partial
                        out.write(chunk)
                        digest.update(chunk)
                        length += len(chunk)
                        break
                    except (OSError, http.client.HTTPException):
                        break
                    if not chunk:
                        complete = declared is None or length == int(declared)
                        break
                    out.write(chunk)
                    digest.update(chunk)
                    length += len(chunk)
                out.flush()
                os.fsync(out.fileno())
            os.replace(partial, self.path)
            if os.name == "posix":
                descriptor = os.open(self.directory, os.O_RDONLY | os.O_DIRECTORY)
                try:
                    os.fsync(descriptor)
                finally:
                    os.close(descriptor)
        except OSError:
            self.status, self.failure = "archive_error", "archive_error"
            raise
        self.body_bytes = length
        self.sha256 = digest.hexdigest()
        self.status = "complete" if complete else "partial"
        if not complete:
            self.failure = "incomplete_body"
        # Persist the capture independently of the outcome of parsing or metering.
        with closing(sqlite3.connect(self.ledger)) as db, db:
            self.save(db)
